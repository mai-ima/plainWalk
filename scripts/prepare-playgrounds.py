#!/usr/bin/env python3
"""Generate a standalone app playground from the canonical iOS/Web sources."""
from pathlib import Path
import hashlib, json, plistlib, shutil, zipfile

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / 'ios/Playgrounds/PlainWalk.swiftpm'
TARGET = PACKAGE / 'Sources/AppModule'
if not (ROOT / 'dist/data/japan-municipalities.geojson').is_file():
    raise SystemExit('Run npm run build first.')
if TARGET.exists():
    shutil.rmtree(TARGET)
TARGET.mkdir(parents=True)
for source in sorted((ROOT / 'ios/PlainWalk').glob('*.swift')):
    if source.name in ['HealthService.swift', 'LiveActivityService.swift']:
        continue
    text = source.read_text()
    if source.name == 'NativeBridge.swift':
        text = text.replace('Bundle.main.url(forResource: "Web", withExtension: nil)', 'Bundle.module.url(forResource: "Web", withExtension: nil)')
        text = text.replace('"healthAvailable": true', '"healthAvailable": false, "flavor": "playgrounds"')
    if source.name == 'LocationRecorder.swift':
        text = text.replace('manager.allowsBackgroundLocationUpdates = recordingRequested', 'manager.allowsBackgroundLocationUpdates = false // App playground: foreground recording only.')
    (TARGET / source.name).write_text('// Generated by scripts/prepare-playgrounds.py; edit ios/PlainWalk instead.\n' + text)
(TARGET / 'PlaygroundsServices.swift').write_text('''import Foundation

// App playgrounds do not embed the HealthKit entitlement or a Live Activity extension.
final class HealthService {
    func authorize() async throws { throw NativeError.message("Playgrounds 版ではヘルスケアを利用できません。Xcode 版をお使いください。") }
    func steps() async throws -> Double? { try await authorize(); return nil }
    func workouts() async throws -> [[String: Any]] { try await authorize(); return [] }
    func route(id: String) async throws -> [[String: Any]] { try await authorize(); return [] }
}
@MainActor final class LiveActivityService {
    func update(_ session: NativeSession?) {}
}
''')
resources = TARGET / 'Resources'
resources.mkdir()
shutil.copytree(ROOT / 'dist', resources / 'Web')
shutil.copytree(ROOT / 'ios/PlainWalk/Assets.xcassets', resources / 'Assets.xcassets')
shutil.copy2(ROOT / 'ios/PlainWalk/PrivacyInfo.xcprivacy', resources / 'PrivacyInfo.xcprivacy')
original = plistlib.loads((ROOT / 'ios/PlainWalk/Info.plist').read_bytes())
info = {key: value for key, value in original.items() if key.startswith(('NSLocation', 'NSMotion', 'NSCamera', 'NSPhoto', 'NSMicrophone'))}
info['CFBundleDisplayName'] = 'PlainWalk Playground'
info['CFBundleDevelopmentRegion'] = 'ja'
info['ITSAppUsesNonExemptEncryption'] = False
# Keep foreground permissions; do not claim background or health entitlements.
info.pop('NSLocationAlwaysAndWhenInUseUsageDescription', None)
(PACKAGE / 'AppInfo.plist').write_bytes(plistlib.dumps(info))
files = {str(p.relative_to(TARGET)): hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted(TARGET.rglob('*')) if p.is_file()}
(PACKAGE / 'Sources/generated-manifest.json').write_text(json.dumps({'generator': 'scripts/prepare-playgrounds.py', 'files': files}, indent=2) + '\n')
output = ROOT / 'artifacts/packages/PlainWalk.swiftpm.zip'
output.parent.mkdir(parents=True, exist_ok=True)
with zipfile.ZipFile(output, 'w', zipfile.ZIP_DEFLATED) as archive:
    for path in sorted(PACKAGE.rglob('*')):
        if path.is_file() and not any(part in ['.build', '.swiftpm'] for part in path.relative_to(PACKAGE).parts):
            archive.write(path, Path('PlainWalk.swiftpm') / path.relative_to(PACKAGE))
print(f'Generated {PACKAGE.relative_to(ROOT)} ({len(files)} source/resource files).')
print(f'Ready-to-open archive: {output.relative_to(ROOT)}')
